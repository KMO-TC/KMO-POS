export function translateText(value, language) {
  if (typeof value !== 'string' || language !== 'en') return value;

  const leading = value.match(/^\s*/)?.[0] || '';
  const trailing = value.match(/\s*$/)?.[0] || '';
  const content = value.trim().replace(/\s+/g, ' ');
  if (!content) return value;

  const directTranslation = englishTranslations[content];
  if (directTranslation) return `${leading}${directTranslation}${trailing}`;

  let translated = content;
  for (const [source, replacement] of phraseTranslations) {
    translated = translated.split(source).join(replacement);
  }
  return `${leading}${translated}${trailing}`;
}
